<?php

if (session_status() === PHP_SESSION_NONE) {
    session_start();
}


/*
|--------------------------------------------------------------------------
| CEK LOGIN
|--------------------------------------------------------------------------
*/

function sudahLogin()
{
    return isset($_SESSION['user_id']);
}


/*
|--------------------------------------------------------------------------
| WAJIB LOGIN
|--------------------------------------------------------------------------
*/

function wajibLogin()
{
    if (!sudahLogin()) {
        header("Location: ../login.php");
        exit;
    }
}


/*
|--------------------------------------------------------------------------
| WAJIB ROLE
|--------------------------------------------------------------------------
*/

function wajibRole($role)
{
    wajibLogin();

    if (
        !isset($_SESSION['role']) ||
        $_SESSION['role'] !== $role
    ) {
        header("Location: ../index.php");
        exit;
    }
}


/*
|--------------------------------------------------------------------------
| MENDAPATKAN USER ID
|--------------------------------------------------------------------------
*/

function userId()
{
    return (int)($_SESSION['user_id'] ?? 0);
}